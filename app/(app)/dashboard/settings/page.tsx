'use client';

import React, { useState } from 'react';
import {
  Settings,
  Shield,
  Download,
  Trash2,
  Bell,
  Moon,
  Sun,
  Globe,
  Lock,
  BarChart3,
  Check,
  AlertTriangle,
} from 'lucide-react';
import { Button } from '@/components/ui/button';

export default function SettingsPage() {
  const [locale, setLocale] = useState('en');
  const [theme, setTheme] = useState<'dark' | 'light'>('dark');
  const [checkinsEnabled, setCheckinsEnabled] = useState(true);
  const [checkinTime, setCheckinTime] = useState('09:00');
  const [savedNote, setSavedNote] = useState<string | null>(null);

  // Trigger export of all personal user data as JSON download
  const handleExportData = () => {
    const exportPayload = {
      user: {
        name: 'Arya',
        email: 'user@example.com',
        preferred_locale: locale,
        exported_at: new Date().toISOString(),
      },
      mood_entries: [
        { date: '2026-10-10', score: 4, note: 'Daily checkin' },
        { date: '2026-10-09', score: 3, note: 'Chamomile tea' },
      ],
      journal_entries: [
        { date: '2026-10-10', title: 'Feeling a bit anxious but also hopeful' },
      ],
      disclaimer: 'Personal wellness data archive generated by Leyla.',
    };

    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(exportPayload, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute('href', dataStr);
    downloadAnchor.setAttribute('download', `leyla_my_data_${new Date().toISOString().slice(0, 10)}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();

    showNotification('Personal data archive successfully downloaded.');
  };

  const handleClearChatHistory = () => {
    if (confirm('Are you sure you want to clear your conversation history with Leyla?')) {
      showNotification('Chat history cleared.');
    }
  };

  const handleDeleteAccount = () => {
    if (
      confirm(
        'WARNING: Are you sure you want to permanently delete your Leyla account? All journals, mood logs, and account records will be permanently erased.'
      )
    ) {
      alert('Your account and all associated data have been requested for permanent deletion.');
      window.location.href = '/';
    }
  };

  const showNotification = (msg: string) => {
    setSavedNote(msg);
    setTimeout(() => setSavedNote(null), 3500);
  };

  const toggleTheme = (newTheme: 'dark' | 'light') => {
    setTheme(newTheme);
    if (newTheme === 'light') {
      document.documentElement.classList.remove('dark');
      document.documentElement.classList.add('light');
    } else {
      document.documentElement.classList.remove('light');
      document.documentElement.classList.add('dark');
    }
    showNotification(`Theme set to ${newTheme} mode.`);
  };

  return (
    <div className="space-y-8 pb-12">
      {/* Header */}
      <div>
        <h2 className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight flex items-center gap-2.5">
          <Settings className="h-6 w-6 text-purple-400" />
          <span>Settings &amp; Privacy Center</span>
        </h2>
        <p className="text-xs text-purple-200/70 mt-1">
          Full control over your preferences, appearance, notifications, and data sovereignty.
        </p>
      </div>

      {savedNote && (
        <div className="rounded-2xl border border-emerald-500/30 bg-emerald-950/40 p-3.5 text-xs text-emerald-200 flex items-center gap-2 animate-fade-in">
          <Check className="h-4 w-4 text-emerald-400" />
          <span>{savedNote}</span>
        </div>
      )}

      {/* Preferences Section */}
      <div className="rounded-3xl border border-purple-500/20 bg-gradient-to-b from-[#16102a]/95 to-[#100c22]/95 p-6 sm:p-7 shadow-xl backdrop-blur-xl space-y-6">
        <h3 className="text-base font-bold text-white flex items-center gap-2">
          <Globe className="h-4 w-4 text-purple-400" />
          <span>Language &amp; Appearance</span>
        </h3>

        <div className="grid grid-cols-1 sm:grid-cols-2 gap-6">
          {/* Language Selector */}
          <div>
            <label className="block text-xs font-semibold text-purple-200/80 mb-2">
              Companion Language
            </label>
            <select
              value={locale}
              onChange={(e) => {
                setLocale(e.target.value);
                showNotification('Language preference saved.');
              }}
              className="w-full rounded-xl border border-purple-500/20 bg-[#0d0a1b] py-2.5 px-3 text-xs text-white focus:border-purple-400 focus:outline-none"
            >
              <option value="en">English</option>
              <option value="hi">हिन्दी (Hindi)</option>
              <option value="te">తెలుగు (Telugu)</option>
              <option value="ta">தமிழ் (Tamil)</option>
            </select>
          </div>

          {/* Theme Switcher */}
          <div>
            <label className="block text-xs font-semibold text-purple-200/80 mb-2">
              Color Theme
            </label>
            <div className="flex items-center gap-2 bg-purple-950/30 p-1 rounded-xl border border-purple-500/20">
              <button
                type="button"
                onClick={() => toggleTheme('dark')}
                className={`flex-1 flex items-center justify-center gap-1.5 py-1.5 rounded-lg text-xs font-semibold transition-colors ${
                  theme === 'dark' ? 'bg-purple-600 text-white' : 'text-purple-300/70 hover:text-white'
                }`}
              >
                <Moon className="h-3.5 w-3.5" /> Dark Twilight
              </button>
              <button
                type="button"
                onClick={() => toggleTheme('light')}
                className={`flex-1 flex items-center justify-center gap-1.5 py-1.5 rounded-lg text-xs font-semibold transition-colors ${
                  theme === 'light' ? 'bg-purple-600 text-white' : 'text-purple-300/70 hover:text-white'
                }`}
              >
                <Sun className="h-3.5 w-3.5" /> Soft Light
              </button>
            </div>
          </div>
        </div>

        {/* Proactive Check-in preferences */}
        <div className="pt-6 border-t border-purple-500/10 space-y-4">
          <div className="flex items-center justify-between">
            <div>
              <h4 className="text-sm font-bold text-white flex items-center gap-2">
                <Bell className="h-4 w-4 text-purple-400" />
                <span>Proactive Companion Check-ins</span>
              </h4>
              <p className="text-xs text-purple-200/60 mt-0.5">
                Gentle reminders once a day to check in on your emotions.
              </p>
            </div>
            <input
              type="checkbox"
              checked={checkinsEnabled}
              onChange={(e) => {
                setCheckinsEnabled(e.target.checked);
                showNotification(`Proactive check-ins ${e.target.checked ? 'enabled' : 'disabled'}.`);
              }}
              className="h-5 w-5 accent-purple-600 rounded cursor-pointer"
            />
          </div>

          {checkinsEnabled && (
            <div className="max-w-xs">
              <label className="block text-xs font-semibold text-purple-200/80 mb-1">
                Preferred Check-in Time
              </label>
              <input
                type="time"
                value={checkinTime}
                onChange={(e) => {
                  setCheckinTime(e.target.value);
                  showNotification('Check-in time updated.');
                }}
                className="rounded-xl border border-purple-500/20 bg-[#0d0a1b] py-2 px-3 text-xs text-white focus:border-purple-400 focus:outline-none"
              />
            </div>
          )}
        </div>
      </div>

      {/* Privacy Center & Data Sovereignty */}
      <div className="rounded-3xl border border-purple-500/20 bg-gradient-to-b from-[#16102a]/95 to-[#100c22]/95 p-6 sm:p-7 shadow-xl backdrop-blur-xl space-y-6">
        <h3 className="text-base font-bold text-white flex items-center gap-2">
          <Shield className="h-4 w-4 text-emerald-400" />
          <span>Privacy Center &amp; Data Sovereignty</span>
        </h3>

        <div className="space-y-4">
          {/* Export Data */}
          <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 p-4 rounded-2xl border border-purple-500/15 bg-white/[0.02]">
            <div>
              <h4 className="text-sm font-bold text-white">Export All My Data</h4>
              <p className="text-xs text-purple-200/60 mt-0.5">
                Download a complete JSON export of all your mood logs, journal reflections, and habits.
              </p>
            </div>
            <Button
              variant="outline"
              size="sm"
              onClick={handleExportData}
              className="rounded-xl border-purple-500/30 text-xs text-purple-200 hover:text-white"
            >
              <Download className="h-3.5 w-3.5 mr-1.5" />
              Download JSON
            </Button>
          </div>

          {/* Clear Chat History */}
          <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 p-4 rounded-2xl border border-purple-500/15 bg-white/[0.02]">
            <div>
              <h4 className="text-sm font-bold text-white">Clear Chat History</h4>
              <p className="text-xs text-purple-200/60 mt-0.5">
                Delete all previous messages exchanged with Leyla from your device and database.
              </p>
            </div>
            <Button
              variant="outline"
              size="sm"
              onClick={handleClearChatHistory}
              className="rounded-xl border-purple-500/30 text-xs text-purple-200 hover:text-white"
            >
              <Trash2 className="h-3.5 w-3.5 mr-1.5" />
              Clear History
            </Button>
          </div>

          {/* Delete Account */}
          <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 p-4 rounded-2xl border border-rose-500/25 bg-rose-950/20">
            <div>
              <h4 className="text-sm font-bold text-rose-300">Delete Account &amp; All Data</h4>
              <p className="text-xs text-rose-200/60 mt-0.5">
                Permanently purge your account, journal records, and files. This action cannot be reversed.
              </p>
            </div>
            <Button
              variant="destructive"
              size="sm"
              onClick={handleDeleteAccount}
              className="rounded-xl text-xs font-bold"
            >
              <Trash2 className="h-3.5 w-3.5 mr-1.5" />
              Delete Account
            </Button>
          </div>
        </div>
      </div>

      {/* Institutional Layer: Campus Wellbeing & Safety Review Console */}
      <div className="rounded-3xl border border-purple-500/20 bg-gradient-to-b from-[#16102a]/95 to-[#100c22]/95 p-6 sm:p-7 shadow-xl backdrop-blur-xl space-y-6">
        <div className="flex items-center justify-between">
          <h3 className="text-base font-bold text-white flex items-center gap-2">
            <BarChart3 className="h-4 w-4 text-cyan-400" />
            <span>Campus Wellbeing Dashboard (Anonymized Aggregate)</span>
          </h3>
          <span className="text-[10px] text-cyan-300 bg-cyan-950/60 border border-cyan-500/30 px-2.5 py-0.5 rounded-full font-bold">
            Min Group Size &ge; 10
          </span>
        </div>

        <p className="text-xs text-purple-200/70 leading-relaxed">
          Designed for university wellness departments and campus mental health teams. To safeguard student privacy, no individual logs or message transcripts are ever accessible. Only cohort-level trends with at least 10 active participants are aggregated.
        </p>

        <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 pt-2">
          <div className="p-4 rounded-2xl border border-purple-500/15 bg-white/[0.02]">
            <span className="text-xs text-purple-300/60 block">Cohort Average Mood</span>
            <span className="text-2xl font-bold text-white mt-1 block">3.7 / 5.0</span>
            <span className="text-[11px] text-emerald-400 font-semibold mt-1 block">Stable (+0.2 pts)</span>
          </div>

          <div className="p-4 rounded-2xl border border-purple-500/15 bg-white/[0.02]">
            <span className="text-xs text-purple-300/60 block">Check-in Completion Rate</span>
            <span className="text-2xl font-bold text-white mt-1 block">76%</span>
            <span className="text-[11px] text-purple-300/60 font-semibold mt-1 block">340 active students</span>
          </div>

          <div className="p-4 rounded-2xl border border-purple-500/15 bg-white/[0.02]">
            <span className="text-xs text-purple-300/60 block">Safety Event Interventions</span>
            <span className="text-2xl font-bold text-white mt-1 block">12</span>
            <span className="text-[11px] text-rose-300 font-semibold mt-1 block">Routed to 988 / Helplines</span>
          </div>
        </div>
      </div>
    </div>
  );
}
